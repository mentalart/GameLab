'use strict';

const v1 = require('./urok-01');

const lesson = JSON.parse(JSON.stringify(v1)); // своя копия: первая версия не меняется
const step = id => lesson.checkpoints.flatMap(cp => cp.steps).find(s => s.id === id);
const cp = id => lesson.checkpoints.find(c => c.id === id);

// версия 1 (программист через API) убрана из меню учителя: все игры курса собираются в чате Qwen (решение автора 18.10.2026)
delete lesson.hidden;
Object.assign(lesson, {
  id: 'urok-01-v2',
  version: 2,
  title: v1.title,
  programmer: 'chat', // lib/ai.js: сборка, правка и починка игр идут через chat.qwen.ai копированием
});

cp('vau').teacher.say = 'Сегодня вы геймдизайнеры. Сейчас при вас ИИ соберёт игру из пяти безумных карт: я отдам задание Qwen в чате, а код вставлю в портал. Код пишет он, а что почувствует игрок, решаете вы.';
cp('vau').teacher.watch = 'Вкладка «Вау-старт»: голоса «перетянуть», гейм дизайн документ и сборка (в игру-страницу из задания Clear бот-плейтестер не играет). «Собрать» открывает окно Qwen: скопируйте задание в новый чат chat.qwen.ai, дождитесь ответа и вставьте его в окно. Пока Qwen пишет, класс играет в донор и заполняет анкету.';

Object.assign(step('sborka'), {
  text: 'Программист — Qwen в чате chat.qwen.ai. Жми «Собрать»: портал даст задание, скопируй его в новый чат, дождись кода и вставь ответ в окно портала. Если ответ не подошёл или оборвался, портал скажет, что написать в чат дальше.',
});

const peremena = cp('peremena');
peremena.teacher.say = 'Кто ещё не вставил код из чата — сначала вставьте ответ Qwen в портал, потом отдыхайте. Игра сохранится в портале.';
peremena.teacher.watch = 'Таблица учеников, колонка «Игра»: у кого пусто — тот не дождался ответа Qwen или не вставил его. Ошибку запуска страница ученика превращает в сообщение для того же чата.';
step('peremena-text').html = `<p>Если Qwen ещё пишет — дождись ответа и вставь его в окно портала. Игра сохранится в портале.</p>
<p>После перемены — первая партия в своей игре, ручки геймдизайнера и правки.</p>`;

// правки без лимита: каждая правка — новое сообщение Qwen в том же чате
const m1 = step('masterskaya'), m2 = step('masterskaya-2');
delete m1.limit; delete m2.limit;
// правка своими словами прямо в чате Qwen (решение автора 18.10.2026): портал подсказывает просьбу и принимает новую версию в любой момент
m1.text = 'Первая правка — до плейтеста. Главная находка разбора уже в просьбе. Напиши Qwen сам, в том чате, где он писал игру: можно скопировать просьбу из конструктора или сказать своими словами. Ответ вставь кнопкой «Вставить новую версию из чата». Одна просьба за раз, числа — ручками (Tab).';
m2.text = 'На доске — что хочется соседям, их «а что если» и твои находки разбора. Возьми одну карточку, напиши Qwen в тот же чат и вставь ответ. Каждая правка — новая версия игры, откатить можно в любой момент. Хочешь сложнее — возьми цель уровня «Продвинутый»: вторая механика.';

module.exports = lesson;
